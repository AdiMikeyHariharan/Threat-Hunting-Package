"""The bundled sample logs must keep demonstrating what they were built for.

auth.log, enterprise_sim.log and attack_sim.log are generated by
scripts/generate_sample_logs.py; portscan.log is a real nmap capture from
scripts/simulate_scan.py.
"""

from collections import defaultdict
from pathlib import Path

import pytest

from siem_hunter.pipeline import Pipeline

ROOT = Path(__file__).resolve().parents[1]


def _detections(name: str) -> list[dict]:
    return Pipeline(rules_dir=ROOT / "rules").analyze(ROOT / "sample_data" / name, fmt="syslog")["detections"]


def _entities(detections: list[dict]) -> dict[str, set]:
    out = defaultdict(set)
    for d in detections:
        out[d["rule_id"]].add(d["entity"])
    return out


@pytest.mark.parametrize("name, expected", [
    ("auth.log", {
        "SSH-BRUTE-0001", "SSH-INVALID-USER-0001", "SSH-ROOT-LOGIN-0001",
        "NEW-ACCOUNT-0001", "SUDO-ABUSE-0001", "ANOMALY-VOLUME-0001",
    }),
    ("enterprise_sim.log", {
        "PWD-SPRAY-0001", "CRED-STUFF-0001", "SSH-ROOT-LOGIN-0001", "OFFHOURS-ROOT-0001",
        "PRIVGRP-0001", "SUDO-ROOT-SHELL-0001", "FW-DISABLE-0001", "PASSWD-CHANGE-0001",
        "ROOT-ACCOUNT-0001", "NEW-ACCOUNT-0001", "ANOMALY-VOLUME-0001",
    }),
    ("attack_sim.log", {
        "PORT-SCAN-0001", "PWD-SPRAY-0001", "SSH-INVALID-USER-0001", "CRED-STUFF-0001",
        "SSH-BRUTE-0001", "SSH-ROOT-LOGIN-0001", "OFFHOURS-ROOT-0001", "NEW-ACCOUNT-0001",
        "ROOT-ACCOUNT-0001", "PASSWD-CHANGE-0001", "PRIVGRP-0001", "SUDO-ABUSE-0001",
        "SUDO-ROOT-SHELL-0001", "FW-DISABLE-0001", "ANOMALY-VOLUME-0001",
    }),
])
def test_every_planted_attack_step_is_detected(name, expected):
    assert {d["rule_id"] for d in _detections(name)} == expected


@pytest.mark.parametrize("name, staff_ips", [
    ("auth.log", {"10.0.4.21", "10.0.4.55", "10.0.4.38", "10.0.4.62", "10.0.4.10"}),
    ("enterprise_sim.log", {f"10.0.5.{n}" for n in range(31, 39)} | {"10.0.5.20"}),
    ("attack_sim.log", {"10.0.7.31", "10.0.7.44", "10.0.7.58", "10.0.7.62", "10.0.7.12"}),
])
def test_normal_staff_activity_raises_no_alerts(name, staff_ips):
    assert not [d for d in _detections(name) if d["entity"] in staff_ips]


def test_auth_log_attack_is_attributed_to_the_brute_forcer():
    by_rule = _entities(_detections("auth.log"))
    assert by_rule["SSH-BRUTE-0001"] == by_rule["ANOMALY-VOLUME-0001"] == {"45.83.19.7"}
    assert len(_detections("auth.log")) == 7  # documented in README and ARCHITECTURE


def test_enterprise_sim_attribution():
    by_rule = _entities(_detections("enterprise_sim.log"))
    assert by_rule["PWD-SPRAY-0001"] == by_rule["ANOMALY-VOLUME-0001"] == {"198.51.100.23"}
    assert by_rule["CRED-STUFF-0001"] == {"admin"}
    assert by_rule["OFFHOURS-ROOT-0001"] == {"10.0.5.9"}       # root via the jump host at 03:12


def test_attack_sim_attribution():
    detections = _detections("attack_sim.log")
    by_rule = _entities(detections)
    assert by_rule["PORT-SCAN-0001"] == by_rule["ANOMALY-VOLUME-0001"] == {"203.0.113.66"}
    assert by_rule["CRED-STUFF-0001"] == {"bob"}
    assert by_rule["OFFHOURS-ROOT-0001"] == {"203.0.113.66", "10.0.7.20"}  # intrusion + lateral hop
    # One NEW-ACCOUNT alert is the attack's backdoor, the other an admin's legitimate intern account.
    assert len([d for d in detections if d["rule_id"] == "NEW-ACCOUNT-0001"]) == 2


def test_portscan_fast_scan_is_caught_and_slow_scan_evades():
    log = (ROOT / "sample_data" / "portscan.log").read_text().splitlines()
    slow_lines = [l for l in log if 9300 <= int(l.rsplit(" ", 1)[1]) <= 9314]
    assert len({l.rsplit(" ", 1)[1] for l in slow_lines}) >= 15     # the slow scan really happened

    scans = [d for d in _detections("portscan.log") if d["rule_id"] == "PORT-SCAN-0001"]
    assert scans, "the fast nmap scan must be detected"
    flagged_ports = {int(p) for d in scans for p in d["context"]["distinct_values"]}
    assert flagged_ports.isdisjoint(range(9300, 9315))              # low-and-slow evades the 10 s window
